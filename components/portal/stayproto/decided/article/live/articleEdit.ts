/**
 * 宿の記事(/stay/article/{id})の「見本どおりの短さ」にするための編集表(宿の ID ごと)。
 *
 * 見本の記事は 1 節が見出し 2 行・本文 4〜5 行しかない。stay.json の記事(Place.article)は事実を網羅していて 1 節が 250〜350 字あるので、
 * ここで「どの文を」「どの順で」「どの見出しの下に」出すかだけを決める。決まりは 3 つ。
 *  1. 本文は、記事の中の文をそのまま抜き出す(pick = 文の頭の数文字。記事に無い文・点検(stayLineOk)に通らない文は出ない)。言い換えない・足さない。
 *  2. 見出し・時刻・「宿の基本」の短い語は、記事の事実から取った語だけ。時刻・基本の各項目には、根拠になる記事の言い回し(need)を付け、
 *     その言い回しが記事の文に無ければ(記事が作り直されて変わったとき)その項目を出さない。
 *  3. 載せない事実は節を増やさずに削る(住所・電話・道順・細かな数字は宿の情報の箱と「宿の基本」へ)。
 *
 * この表に無い宿は、articleData.ts の自動の組み立て(場所の節を除いて先頭の文から)で出る。
 */

/** 写真の種類(stay.json の写真の種類 = 外観・客室・風呂・料理・共用・景色) */
export type PhotoKind = "exterior" | "room" | "bath" | "food" | "common" | "view";

export type EditSection = {
  /** 番号の横の小さな語(見本の「温泉」「お食事」「お部屋」) */
  kicker: string;
  /** 見出し(1〜2 行。行の切れ目) */
  heading: string[];
  /** 本文に出す文(記事の中の文の頭。順に出す) */
  pick: string[];
  /** 振り分ける写真の種類 */
  kind: PhotoKind;
};

/** 時刻の線の 1 点(t = 時刻。l = 何の時刻か。s = 補足。need = 根拠の言い回し) */
export type EditTime = { t: string; l: string; s?: string; need: string };
/** 「宿の基本」の 1 項目(t = 太く出す値。l = 何か。s = 補足。need = 根拠の言い回し) */
export type EditBasic = { t: string; l: string; s?: string; need: string };

export type ArticleEdit = {
  /** 3 つの節(見本の 01・02・03) */
  sections: EditSection[];
  /** 03 の右の一言(記事の中の 1 文の頭) */
  quote?: string;
  /** 04 を時刻の横並びにする(2 つ以上確かめられたときだけ。足りなければ「宿の基本」) */
  times?: EditTime[];
  /** 「宿の基本」の項目(所在地・電話は住所・電話の値から自動で先頭に付く。ここは残りの 3 つまで) */
  basics?: EditBasic[];
};

