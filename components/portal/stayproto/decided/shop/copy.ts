/**
 * 宿の紹介ページの短い文(見本どおりの短さ: 見出し 2 行・本文 3〜4 行)。宿ごとに、紹介記事の「事実」だけから書いた。
 * 出どころ = automation/vertical-stores/articles/lodging-*.json の facts(公式サイト・Google マップで確認した事実)。
 * 宿 ID → 記事の対応: st0001=lodging-4 / st0002=lodging-5 / st0003=lodging-6 / st0004=lodging-7 / st0005=lodging-8 / st0006=lodging-12 / st0007=lodging-13 / st0008=lodging-14。
 * 画面に出す直前に、1 文ずつ stayLineOk(料金・評価・最上級・癒し・効き目・泊まった体験の言い回し)を通す(data.ts)。
 * ここに無い宿は data.ts の自動の短文(記事の最初の事実の文)で出る。
 *
 * 節の並び = 先頭は「客室」(横送りの写真。宿の種類に合わせて「サイト」「コテージ」など)・2 つめは「温泉」→ 温泉の札が無ければ「お風呂」→ お風呂が無ければ
 * 「共用スペース」「庭」など・3 つめは「お食事」→ 食事を出さない宿は「キッチン」「BBQ」など。2 つめ・3 つめは、その節に使える写真があるときだけ出す。
 */

/** 写真の種類。living = 客室の写真のうち居間・リビング・食堂・広間(寝室ではないもの。一棟貸しの宿の「居間」の節に使う) */
export type PKind = "exterior" | "view" | "rooms" | "living" | "bath" | "dining" | "common" | "other";

export type SecCopy = {
  /** 節の位置(a = 客室 / b = 温泉・お風呂・共用 / c = お食事・キッチン)。タブの飛び先 id にもなる */
  slot: "a" | "b" | "c";
  /** タブ・節の見出しの字と、その下の英字 */
  label: string;
  en: string;
  /** 2 行の見出し */
  h: [string, string];
  /** 短い本文(1 文ずつ) */
  p: string[];
  /** 「〇〇の詳細を見る」で開く全文の元になる、記事の節の見出し(stay.json の article.sections[].heading) */
  from: string[];
  /** 写真の種類の優先順(先に書いた種類から、上限の枚数まで使う。ここに書いた種類は、その節の写真として合う) */
  kinds: PKind[];
};

export type FactBox = { icon: RowIcon; l: string; v: string };

export type ShopCopy = {
  /** ヒーローの 1 行 */
  tag: string;
  /** 右上の箱の大きな字(宿の種類。記事の言い方) */
  big: string;
  pills?: string[];
  boxes: FactBox[];
  intro: { h: [string, string]; p: string[] };
  secs: SecCopy[];
  fac: Array<{ k: FacKey; t: string }>;
  /** 基本情報の表(上から順)。v が無い行は、宿のデータの値(所在地 / 電話番号 / 公式サイト / 種類)を入れる。note は値の後ろに添える字 */
  rows: Array<{ k: string; v?: string; note?: string }>;
  access: Array<{ icon: RowIcon; label: string; text: string }>;
  /** 「詳しいアクセス情報を見る」で開く節の見出し */
  accessFrom: string[];
};

