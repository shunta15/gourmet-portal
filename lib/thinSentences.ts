/** 何か取る物があるか（無ければ何もせずそのまま返す。速さのための前判定ではなく、文ごとの完全一致なので偽陽性はない） */
function dropSentence(s: string): string | null {
  if (!THIN_SET.has(s.trim())) return null;
  return /^\s*/.exec(s)?.[0] ?? ""; // 文の前の改行・空白（段落の区切り）は残す
}

/** 1 つの文章（段落・導入・説明）から、表にある文を取り除く。何も無ければそのまま返す */
export function stripThinSentences(text: string): string;
export function stripThinSentences(text: string | undefined): string | undefined;
export function stripThinSentences(text: string | undefined): string | undefined {
  if (!text || typeof text !== "string") return text;
  const sentences = text.match(/[^。]*。|[^。]+$/g);
  if (!sentences) return text;
  let changed = false;
  const fixed = sentences.map((s) => {
    const r = dropSentence(s);
    if (r === null) return s;
    changed = true;
    return r;
  });
  return changed ? fixed.join("") : text;
}

/** 文章の並び（本文の段落・特徴）に通す。丸ごと取れて空になった項目は並びから外す。何も変わらなければ同じ配列を返す */
export function stripThinSentencesList(items: string[]): string[];
export function stripThinSentencesList(items: string[] | undefined): string[] | undefined;
export function stripThinSentencesList(items: string[] | undefined): string[] | undefined {
  if (!items) return items;
  let changed = false;
  const next: string[] = [];
  for (const t of items) {
    const f = typeof t === "string" ? stripThinSentences(t) : t;
    if (f !== t) changed = true;
    if (typeof f === "string" && f.trim() === "" && f !== t) continue;
    next.push(f);
  }
  return changed ? next : items;
}
